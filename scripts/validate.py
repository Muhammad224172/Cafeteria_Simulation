"""Validation against the two Arena models (reference numbers in validation/arena_reference.yaml).

Uses the per-replication outputs written by run_baseline.py. Our replications and Arena's use
unrelated random numbers, so the comparison is a Welch two-sample t-test on replication means.

Writes results/validation.json and results/validation.md.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import yaml
from _common import RESULTS, ROOT, write_json
from scipy import stats

from cafesim.analysis import t_ci


def welch(ours, ref) -> dict:
    r = stats.ttest_ind(ours, ref, equal_var=False)
    return {"diff": float(np.mean(ours) - np.mean(ref)), "p_value": float(r.pvalue)}


def main() -> None:
    ref = yaml.safe_load((ROOT / "validation" / "arena_reference.yaml").read_text(encoding="utf-8"))
    reps = pd.read_csv(RESULTS / "baseline" / "scenario_replications.csv")
    inst = ref["instructor_solution_base"]
    i_m1 = np.asarray(inst["measure1_s"]["per_replication"])
    i_m2 = np.asarray(inst["measure2"]["per_replication"])

    rows = []
    out = {"instructor_solution_base": {}, "group_part2_model": {}}
    for scen, label in (
        ("base", "This model, problem reading (base)"),
        ("s02_instructor_interpretation", "This model, instructor-model reading (s02)"),
    ):
        g = reps[reps["scenario"] == scen]
        m1 = t_ci(g["measure1_s"])
        m2 = t_ci(g["measure2_system_empty"])  # Arena's measure 2 runs until the cafeteria is empty
        end = g["t_empty_s"].mean() / 60
        w1, w2 = welch(g["measure1_s"], i_m1), welch(g["measure2_system_empty"], i_m2)
        out["instructor_solution_base"][scen] = {
            "measure1_s": m1.as_dict(),
            "measure2_system_empty": m2.as_dict(),
            "end_min": end,
            "welch_measure1": w1,
            "welch_measure2": w2,
        }
        rows.append((label, m1, m2, end, w1, w2))

    i1, i2 = t_ci(i_m1), t_ci(i_m2)
    g5 = reps[reps["scenario"] == "s05_group_part2_arrivals"]
    grp = ref["group_part2_model"]
    out["group_part2_model"] = {
        "ours_customers": float(g5["n_customers"].mean()),
        "ours_measure2_until_2000": t_ci(g5["measure2_until_2000"]).as_dict(),
        "ours_sojourn_mean_s": float(g5["sojourn_mean_s"].mean()),
        "arena_customers": grp["customers_created"],
        "arena_wip": grp["customer_wip_time_average"],
        "arena_total_time_s": grp["customer_total_time_mean_s"],
    }
    write_json(RESULTS / "validation.json", out)

    lines = [
        "# Validation against the Arena models",
        "",
        "Generated by `scripts/validate.py` from `results/baseline/scenario_replications.csv` and",
        "`validation/arena_reference.yaml`. 95% t-intervals over 20 replications each. Measure 2 is",
        "averaged until the last diner leaves here, to match the Arena stop rule. p-values are Welch",
        "two-sample tests on replication means (the random numbers are unrelated).",
        "",
        "## Instructor solution model (Part 3 base run, 20 replications)",
        "",
        "| Source | Measure 1 (s) | Measure 2 (customers) | Day ends (min after 11:30) | p (m1) | p (m2) |",
        "|---|---|---|---|---|---|",
        f"| Arena, instructor solution model | {i1.mean:.1f} ± {i1.half_width:.1f}"
        f" | {i2.mean:.1f} ± {i2.half_width:.1f} | {inst['replication_end_min']['mean']:.1f} | | |",
    ]
    for label, m1, m2, end, w1, w2 in rows:
        lines.append(
            f"| {label} | {m1.mean:.1f} ± {m1.half_width:.1f} | {m2.mean:.1f} ± {m2.half_width:.1f} | {end:.1f}"
            f" | {w1['p_value']:.2g} | {w2['p_value']:.2g} |"
        )
    gp = out["group_part2_model"]
    lines += [
        "",
        "## The group's Part 2 model (one replication, fixed 8.5 h)",
        "",
        "| Source | Customers | Time-average number in system, 11:30-20:00 | Mean time in system (s) |",
        "|---|---|---|---|",
        f"| Arena, group Part 2 model | {gp['arena_customers']} | {gp['arena_wip']:.1f}"
        f" | {gp['arena_total_time_s']:.0f} |",
        f"| This model with the same arrival schedule (s05) | {gp['ours_customers']:.0f} |"
        f" {gp['ours_measure2_until_2000']['mean']:.1f} ± {gp['ours_measure2_until_2000']['half_width']:.1f}"
        f" | {gp['ours_sojourn_mean_s']:.0f} |",
        "",
        "See `docs/validation.md` for the discussion.",
        "",
    ]
    (RESULTS / "validation.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
